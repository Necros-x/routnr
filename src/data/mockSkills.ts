export function resolveSkillType(skill: GymnasticSkill): SkillType {
  if (skill.skillType) return skill.skillType;
  if (skill.tags?.includes('Dismount') || skill.elementGroup?.toLowerCase().includes('dismount')) {
    return 'Dismount';
  }
  if (skill.apparatus === 'Vault' || skill.tags?.includes('Vault')) {
    return 'Vault Entry';
  }
  if (skill.tags?.includes('Release') || skill.tags?.includes('Flight') || skill.elementGroup?.toLowerCase().includes('flight') || skill.elementGroup?.toLowerCase().includes('release')) {
    return 'Flight & Release';
  }
  if (skill.tags?.includes('Strength') || skill.tags?.includes('Hold') || skill.tags?.includes('Maltese') || skill.tags?.includes('Cross')) {
    return 'Strength & Hold';
  }
  if (skill.tags?.includes('Pirouette') || skill.tags?.includes('Pivot') || skill.tags?.includes('Spindle') || skill.tags?.includes('Russian')) {
    return 'Turns & Pirouettes';
  }
  if (skill.tags?.includes('Salto') || skill.tags?.includes('Twisting') || skill.elementGroup?.toLowerCase().includes('acrobatic')) {
    return 'Acrobatic / Salto';
  }
  return 'Swings & Circles';
}

export function resolveBodyPart(skill: GymnasticSkill): BodyPartFocus {
  if (skill.bodyPart) return skill.bodyPart;
  const type = resolveSkillType(skill);
  if (type === 'Strength & Hold') return 'Upper Body';
  if (skill.apparatus === 'Pommel Horse' && (skill.tags?.includes('Scissors') || skill.tags?.includes('Flairs'))) {
    return 'Core & Trunk';
  }
  if (type === 'Turns & Pirouettes' || skill.apparatus === 'Pommel Horse' || skill.apparatus === 'Parallel Bars') {
    return 'Upper Body';
  }
  if (type === 'Swings & Circles' && (skill.elementGroup?.toLowerCase().includes('adler') || skill.elementGroup?.toLowerCase().includes('stalder') || skill.tags?.includes('Flairs'))) {
    return 'Core & Trunk';
  }
  if (type === 'Dismount' && skill.apparatus === 'Floor Exercise') {
    return 'Lower Body';
  }
  return 'Full Body';
}

